import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const outDir = path.join(root, 'src', 'game');

const result = await esbuild.build({
  entryPoints: [path.join(outDir, 'runner.js')],
  bundle: true,
  minify: true,
  format: 'iife',
  write: false,
});

const bundledJs = result.outputFiles[0].text;

const html = `<!DOCTYPE html>
<html lang="tr">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no" />
  <style>
    * { margin: 0; padding: 0; box-sizing: border-box; user-select: none; -webkit-user-select: none; }
    html, body { width: 100%; height: 100%; overflow: hidden; background: #0b1020; touch-action: none; }
    canvas { display: block; width: 100%; height: 100%; }
  </style>
</head>
<body>
  <script>${bundledJs}</script>
</body>
</html>`;

const tsContent = `// Auto-generated by scripts/build-game.mjs
export const GAME_HTML = ${JSON.stringify(html)};
`;

fs.writeFileSync(path.join(outDir, 'bundledHtml.ts'), tsContent, 'utf8');
console.log('Generated src/game/bundledHtml.ts (' + Math.round(tsContent.length / 1024) + ' KB)');
